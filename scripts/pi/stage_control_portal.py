#!/usr/bin/env python3
"""Stage the optional port-8085 control portal bind mount, never start Docker.

The Pilot-2 Vue app, DJI authorization, API and MQTT configuration stay intact.
Default mode only inspects files. --apply writes one local Compose overlay.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys
import tempfile


PROJECT = Path(__file__).resolve().parents[2]
EDGE = PROJECT / "cloud-server" / "edge"
PORTAL = PROJECT / "deploy" / "cloud-server" / "control-portal"
OVERLAY = EDGE / "compose.portal.yaml"
TARGET = "/usr/share/nginx/html/aeronexus"


def overlay_contents(portal: Path) -> str:
    """Quote the absolute source path in a YAML-safe representation."""
    path = portal.resolve(strict=True)
    if not path.is_dir():
        raise ValueError("Das Portalverzeichnis ist kein Verzeichnis")
    return (
        "# Opt-in, generated by scripts/pi/stage_control_portal.py.\n"
        "# Only mounts a static, public portal; original DJI Vue files stay intact.\n"
        "services:\n"
        "  control:\n"
        "    volumes:\n"
        "      - type: bind\n"
        f"        source: {json.dumps(str(path))}\n"
        f"        target: {TARGET}\n"
        "        read_only: true\n"
        "        bind:\n"
        "          create_host_path: false\n"
    )


def preflight(edge: Path = EDGE, portal: Path = PORTAL) -> str:
    if not edge.is_dir():
        raise RuntimeError("Lokale Cloud-Edge-Arbeitskopie fehlt")
    for file in (edge / "compose.core.yaml", edge / "compose.brand.yaml"):
        if not file.is_file():
            raise RuntimeError(f"Bestehende Compose-Datei fehlt: {file.name}")
    for file in (portal / "index.html", portal / "fh2.html"):
        if not file.is_file() or file.is_symlink():
            raise RuntimeError(f"Portaldatei fehlt oder ist ein Link: {file.name}")
    return overlay_contents(portal)


def stage(overlay: Path, value: str) -> str:
    """Write only if absent; do not overwrite an operator-modified overlay."""
    if overlay.exists():
        if overlay.is_symlink() or not overlay.is_file():
            raise RuntimeError("Abweichender Overlay-Dateityp")
        if overlay.read_text(encoding="utf-8") != value:
            raise RuntimeError("Lokales compose.portal.yaml weicht von der Vorlage ab – nicht überschrieben")
        return "Bereits korrekt vorbereitet"
    fd, tmp = tempfile.mkstemp(prefix=".portal-", suffix=".yaml", dir=overlay.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(value)
        os.chmod(tmp, 0o600)
        # A concurrent operator file must never be replaced.
        os.link(tmp, overlay)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)
    return "Overlay geschrieben; Docker und Dienste unverändert"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true", help="Compose-Overlay anlegen; KEIN Docker-Restart")
    args = parser.parse_args(argv)
    try:
        desired = preflight(EDGE, PORTAL)
        if OVERLAY.exists():
            if OVERLAY.is_symlink() or OVERLAY.read_text(encoding="utf-8") != desired:
                raise RuntimeError("Vorhandenes compose.portal.yaml unterscheidet sich; Abbruch")
            print("Compose-Overlay bereits vorhanden und passend")
        elif args.apply:
            print(stage(OVERLAY, desired))
        else:
            print("Prüfung OK; Overlay noch nicht vorhanden; keine Datei verändert")
        if not args.apply:
            print("Nächster Schritt: python3 scripts/pi/stage_control_portal.py --apply")
        else:
            print("Aktivierung ist separat und nur für den Container control möglich:")
            print("cd cloud-server/edge")
            print("docker compose -f compose.core.yaml -f compose.brand.yaml -f compose.portal.yaml config --quiet")
            print("docker compose -f compose.core.yaml -f compose.brand.yaml -f compose.portal.yaml up -d --no-deps --no-build --pull never control")
        print("Portalziel: http://<Pi-LAN-IP>:8085/aeronexus/")
        return 0
    except (OSError, RuntimeError, ValueError) as exc:
        # Do not print Docker config or environment variables.
        print(f"PORTAL ABGEBROCHEN ({type(exc).__name__}): {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
